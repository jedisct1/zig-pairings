test "Miller loop output matches the reference vector" {
    const g1 = G1.basePoint;
    const g2 = G2.basePoint;
    const p_affine = g1.affineCoordinates();
    const q_affine = g2.affineCoordinates();

    const f = bls12_381.pairing.millerLoop(p_affine, q_affine);
    const actual_bytes = f.c0.c0.c0.toBytes(.big);

    const expected = parseHex(miller_loop_c0_c0_c0_hex);
    try std.testing.expectEqualSlices(u8, &expected, &actual_bytes);
}

test "Final pairing result matches the reference vector" {
    const g1 = G1.basePoint;
    const g2 = G2.basePoint;

    const result = pairing.pair(g1, g2);
    const actual_bytes = result.c0.c0.c0.toBytes(.big);

    const expected_prefix = parseHex(pairing_result_c0_c0_c0_prefix_hex);
