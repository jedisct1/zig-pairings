test "derived points match the reference vectors" {
    const g1 = G1.basePoint;
    const g2 = G2.basePoint;

    try std.testing.expectEqualSlices(u8, &g1_doubled_compressed, &g1.dbl().toCompressed());
    try std.testing.expectEqualSlices(u8, &g2_doubled_compressed, &g2.dbl().toCompressed());
    try std.testing.expectEqualSlices(u8, &g1_neg_compressed, &g1.neg().toCompressed());
    try std.testing.expectEqualSlices(u8, &g2_neg_compressed, &g2.neg().toCompressed());
    try std.testing.expectEqualSlices(u8, &g1_times_42_compressed, &g1.mul(scalar_42_bytes_le, .little).toCompressed());
    try std.testing.expectEqualSlices(u8, &g2_times_42_compressed, &g2.mul(scalar_42_bytes_le, .little).toCompressed());
    try std.testing.expectEqualSlices(u8, &g1_times_big_compressed, &g1.mul(scalar_big_bytes_le, .little).toCompressed());
    try std.testing.expectEqualSlices(u8, &g2_times_big_compressed, &g2.mul(scalar_big_bytes_le, .little).toCompressed());
}

test "reference vectors decode and encode back to the same bytes" {
    try std.testing.expectEqualSlices(u8, &g1_times_42_compressed, &(try G1.fromCompressed(g1_times_42_compressed)).toCompressed());
    try std.testing.expectEqualSlices(u8, &g2_times_42_compressed, &(try G2.fromCompressed(g2_times_42_compressed)).toCompressed());
}
